const _ = require('lodash');

const formats = ['default', 'oneline', 'csv', 'json', 'html'];

/**
 * Output format from the switches: oneline for --fzf, otherwise --format (default when not given).
 * Throws for an unknown format.
 */
const outputFormat = (switches = {}) => {
  const format = switches.fzf ? 'oneline' : switches.format || 'default';
  if (!formats.includes(format)) {
    throw new Error(`Unknown format '${format}', use one of: ${formats.join(', ')}`);
  }
  return format;
};

const cellText = value => {
  if (_.isNil(value)) {
    return '';
  }
  return _.isObject(value) ? JSON.stringify(value) : String(value);
};

// RFC 4180 quoting: fields with the delimiter, quotes, or line breaks are quoted, quotes doubled
const csvField = (value, delimiter) => {
  const text = cellText(value);
  return text.includes(delimiter) || /["\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};

const toCsv = (records, columns, delimiter = ',') =>
  [columns, ..._.map(records, record => _.map(columns, column => record[column]))]
    .map(row => _.map(row, value => csvField(value, delimiter)).join(delimiter))
    .join('\n');

const escapeHtml = text =>
  cellText(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const htmlTable = ({ heading, records, columns }) =>
  [
    heading ? `<h2>${escapeHtml(heading)}</h2>` : '',
    '<table>',
    `<thead><tr>${_.map(columns, column => `<th>${escapeHtml(column)}</th>`).join('')}</tr></thead>`,
    '<tbody>',
    ..._.map(
      records,
      record =>
        `<tr>${_.map(columns, column => `<td>${escapeHtml(record[column])}</td>`).join('')}</tr>`
    ),
    '</tbody>',
    '</table>'
  ]
    .filter(Boolean)
    .join('\n');

/**
 * Standalone HTML page with a table per section ({ heading, records, columns }), in the light or dark
 * colors of the viewer's system.
 */
const toHtml = (title, sections) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<style>
  :root { --bg: #ffffff; --fg: #1d1d22; --muted: #6b6b76; --line: #e2e2e8; --head: #f4f4f7; }
  @media (prefers-color-scheme: dark) {
    :root { --bg: #16161a; --fg: #e6e6ea; --muted: #9a9aa6; --line: #2c2c34; --head: #1f1f25; }
  }
  body { margin: 0; padding: 24px 16px; background: var(--bg); color: var(--fg);
    font: 14px/1.45 system-ui, -apple-system, "Segoe UI", sans-serif; }
  h1 { font-size: 20px; margin: 0 0 4px; }
  h2 { font-size: 15px; margin: 28px 0 8px; color: var(--muted); }
  .meta { color: var(--muted); margin: 0 0 16px; }
  .scroll { overflow-x: auto; }
  table { border-collapse: collapse; font-variant-numeric: tabular-nums; }
  th, td { text-align: left; padding: 4px 12px 4px 0; border-bottom: 1px solid var(--line);
    vertical-align: top; }
  th { position: sticky; top: 0; background: var(--head); font-weight: 600; }
</style>
</head>
<body>
<h1>${escapeHtml(title)}</h1>
<p class="meta">Generated by musicman on ${escapeHtml(new Date().toISOString())}</p>
${_.map(sections, section => `<div class="scroll">\n${htmlTable(section)}\n</div>`).join('\n')}
</body>
</html>`;

/**
 * Records ({ column: value } objects) in a format other than default. oneline gives one line per
 * record from oneline(record): "key<TAB>colored text", so fzf can show the text and return the key.
 */
const formatRecords = ({ format, title, records, columns, oneline, delimiter }) => {
  const shown = columns || _.uniq(_.flatMap(records, _.keys));
  if (format === 'oneline') {
    return _.map(records, oneline).join('\n');
  }
  if (format === 'csv') {
    return toCsv(records, shown, delimiter);
  }
  if (format === 'json') {
    return JSON.stringify(
      _.map(records, record => _.pick(record, shown)),
      null,
      2
    );
  }
  return toHtml(title, [{ records, columns: shown }]);
};

/**
 * Several record sections ({ heading, records, columns }) in a format other than default, e.g. stats.
 * csv and oneline get a section column, json is an object keyed by heading.
 */
const formatSections = ({ format, title, sections, oneline, delimiter }) => {
  if (format === 'html') {
    return toHtml(title, sections);
  }
  if (format === 'json') {
    return JSON.stringify(
      _.fromPairs(
        _.map(sections, ({ heading, records, columns }) => [
          heading,
          _.map(records, record => _.pick(record, columns))
        ])
      ),
      null,
      2
    );
  }
  const flat = _.flatMap(sections, ({ heading, records }) =>
    _.map(records, record => ({ section: heading, ...record }))
  );
  const columns = ['section', ..._.uniq(_.flatMap(sections, 'columns'))];
  return format === 'csv' ? toCsv(flat, columns, delimiter) : _.map(flat, oneline).join('\n');
};

module.exports = {
  formatRecords,
  formatSections,
  formats,
  outputFormat,
  toCsv,
  toHtml
};
